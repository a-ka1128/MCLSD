// priority: 1000
// Last Stardust — 월드 밖에 남는 설정값 (밸런스 튜닝의 원본)
//
// ── 왜 이 파일이 있나 ──
// persistentData(server.overworld().persistentData)는 ServerLevel의 NBT라 "월드 세이브 안"에 저장된다.
// 그건 진행 상황(가호·각성·관문·위협도·마을)을 담기엔 맞는 자리지만, 밸런스 수치까지 거기 두면
// 월드를 리셋할 때마다 공들여 잡은 튜닝이 통째로 날아간다.
// 이 파일은 kubejs/ 폴더에 있어서 월드 리셋과 무관하게 살아남는다.
//
// ── 사용 규칙 ──
//   · 여기 값 = 기본값(원본). 월드를 새로 파도 이 값으로 시작한다.
//   · /bossdiff 로 인게임에서 바꾼 값 = 라이브 오버라이드(월드 안에 저장, 리셋 시 사라짐).
//   · 읽을 때 우선순위: 라이브 오버라이드 > 이 파일 > 전역 기본값
//   · 인게임에서 실험해 좋은 값을 찾았으면 /bossdiff export 로 뽑아 아래에 박아둔다.
//
// ※ 이 파일은 priority 1000 이라 다른 ls_*.js 보다 먼저 로드된다.

const LS_CONFIG = {
  boss: {
    // 전역 배율(%) — 100 = 모드 원본 그대로
    globalHp: 100,
    globalDmg: 100,

    // 보스별 고정값. /bossdiff export 결과를 여기에 붙여넣으면 영구 반영된다.
    //   'cataclysm:ignis': { hp: 400, dmg: 150 },
    perBoss: {
    }
  },

  // ── 일반 몹 스케일링 (관문 진행도 연동) ──
  // 5성을 찍고 나면 세상의 잡몹이 아무 위협도 안 돼서 탐험이 심심해진다.
  // 관문을 깰수록(= 플레이어가 강해질수록) 세상도 같이 험해지게 한다.
  //
  // ※ 체력보다 공격력을 더 크게 올린다.
  //    체력만 올리면 싸움이 길어질 뿐 지루해지고(스펀지), 긴장감은 공격력에서 나온다.
  //    잡몹은 여전히 빨리 죽되, 방심하면 아파야 한다.
  mob: {
    // 인덱스 = rf_progress (관문 클리어 수 0~4)
    hp:  [1.0, 1.2, 1.5, 1.8, 2.2],
    dmg: [1.0, 1.4, 1.9, 2.5, 3.2],

    // 공격력 상한: 원본 + 이 값을 넘지 않는다.
    // 모드 엘리트 몹은 원본 공격력이 이미 높아서(10+) 배율만 곱하면 2방컷이 난다.
    dmgCapAdd: 20
  }
}

console.log('[Last Stardust] 설정 로드됨 — 보스 전역 ' + LS_CONFIG.boss.globalHp + '% / ' + LS_CONFIG.boss.globalDmg + '%'
  + ' · 개별 ' + Object.keys(LS_CONFIG.boss.perBoss).length + '종')
